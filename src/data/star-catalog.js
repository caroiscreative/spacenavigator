function spectralColor(sp) {
  const c = sp[0];
  if (c === 'O') return '#7090FF';
  if (c === 'B') return '#A8C4FF';
  if (c === 'A') return '#D8E8FF';
  if (c === 'F') return '#FFF8E0';
  if (c === 'G') return '#FFE880';
  if (c === 'K') return '#FFA040';
  if (c === 'M') return '#FF6030';
  return '#FFFFFF';
}

